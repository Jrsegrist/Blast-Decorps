"""Linker scripts and symbol files of the shiftable build (see shiftlib.py).

gen_segment_ld() turns a segment's splat linker script into one where
  * every input section is a unit, between __shu_/__she_ labels;
  * the data section follows the text directly, and .bss the data
    (init inflates hd_code's text and data back to back, then clears from
    the end of the data to the end of RAM);
  * .bss is one NOLOAD section: the objects' own .bss sections plus the
    unmodelled stretches between them (bss_model), in address order;
  * pads (shift tests, or room for later edits) can go before any unit;
  * sections the matching layout never placed (a mod's new .rodata, a new
    file) land in per-section catch-alls at the ends.
"""
import re

from shiftlib import SEGMENTS, SEGTAG, Unit, lowbit_align, die

CATCH_TEXT = ".text"
CATCH_DATA = ".data .data.* .rodata .rodata.* .late_rodata .sdata"
CATCH_BSS = ".bss .bss.* .sbss COMMON .scommon"


def objpath(path, build_dir):
    return re.sub(r"^build/", build_dir.rstrip("/") + "/", path)


def gen_segment_ld(seg, outsecs, bss_items, build_dir, pads=None, vram=None, catch_glob=None,
                   keep_low=None, glued=()):
    """-> (linker script text, [Unit]).

    pads: {(section_kind, unit_ordinal): (label, objpath_or_None, size)} where
    section_kind is "text", "data" or "bss" and unit_ordinal the index (within
    that section's units) of the unit the pad goes before (-1: the end).
    For "bss" pads objpath is None and size the number of bytes.
    keep_low: {unit index: bytes}: space before that unit (shiftbuild.py
    sizes it so the unit keeps the low bits of its original address:
    overrides.txt "lowbits").
    glued: object paths (substrings) that must follow the unit before them
    directly: a table in that unit runs into them (overrides.txt "glue")."""
    pads = pads or {}
    keep_low = keep_low or {}

    def emit_keep(idx, lines):
        if keep_low.get(idx):
            lines.append("        . += 0x%X;   /* overrides.txt lowbits: keep the unit's low address bits */"
                         % keep_low[idx])
    cfg = SEGMENTS[seg]
    tag = SEGTAG[seg]
    units = []
    out = ["/* generated by tools_port/shift/ldgen.py: shiftable link of %s */" % seg, "SECTIONS", "{"]

    def emit_pad(kind, ordinal, lines):
        p = pads.get((kind, ordinal))
        if not p:
            return
        label, obj, size = p
        lines.append("        . = ALIGN(16);")
        lines.append("        %s = .;" % label)
        if obj:
            lines.append("        %s(.%s);" % (obj, "text" if kind == "text" else "data"))
        else:
            lines.append("        . += 0x%X;" % size)
        lines.append("        %s_end = .;" % label)

    text_sec = None
    data_sec = None
    for os_ in outsecs:
        if os_.name == cfg["text"]:
            text_sec = os_
        elif os_.name == cfg["data"]:
            data_sec = os_
        else:
            die("%s: unexpected output section %s" % (seg, os_.name))
    if text_sec is None:
        die("%s: no %s section" % (seg, cfg["text"]))

    def emit_section(os_, kind, at_expr, vram_expr):
        lines = []
        lines.append("    %s %s : AT(%s) SUBALIGN(16)" % (os_.name, vram_expr, at_expr))
        lines.append("    {")
        ordinal = 0
        labels = []         # splat's labels name the unit after them: they go after any pad
        for ent in os_.entries:
            if ent[0] == "label":
                labels.append(ent[1])
                continue
            _, path, secname = ent
            if any(g in path for g in glued) and pads.get((kind, ordinal)):
                die("%s: a pad can't go before %s: the table before it runs into it (overrides.txt glue)" % (seg, path))
            emit_pad(kind, ordinal, lines)
            u = Unit(seg, len(units), "obj", "%s(%s)" % (path, secname), os_.name)
            units.append(u)
            lines.append("        . = ALIGN(16);")
            emit_keep(u.idx, lines)
            lines += ["        %s = .;" % lab for lab in labels]
            labels = []
            lines.append("        %s = .;" % u.label)
            lines.append("        %s(%s);" % (objpath(path, build_dir), secname))
            lines.append("        %s = .;" % u.end_label)
            ordinal += 1
        lines += ["        %s = .;" % lab for lab in labels]
        emit_pad(kind, -1, lines)
        if catch_glob:
            secs = CATCH_TEXT if kind == "text" else CATCH_DATA
            lines.append("        . = ALIGN(16);")
            lines.append("        __shx_%s_%s = .;" % (tag, kind))
            lines.append("        %s;" % " ".join("%s(%s)" % (catch_glob, s) for s in secs.split()))
            lines.append("        __shx_%s_%s_end = .;" % (tag, kind))
        lines.append("        . = ALIGN(16);")
        lines.append("    }")
        return lines

    text_vram = vram if vram is not None else "0x%08X" % text_sec.vram
    out += emit_section(text_sec, "text", "0", text_vram)
    last = text_sec.name
    if data_sec is not None:
        out += emit_section(data_sec, "data", "LOADADDR(%s) + SIZEOF(%s)" % (last, last),
                            "ADDR(%s) + SIZEOF(%s)" % (last, last))
        last = data_sec.name

    # .bss
    bss_name = ".%s_bss" % seg
    if cfg["bss_start"] is not None and seg == "init":
        # init: splat puts nothing in .bss; it starts right after the image (gInflateHuftArena)
        bss_vram = "ADDR(%s) + SIZEOF(%s)" % (last, last)
    else:
        bss_vram = "ADDR(%s) + SIZEOF(%s)" % (last, last)
    lines = ["    %s %s (NOLOAD) : SUBALIGN(16)" % (bss_name, bss_vram), "    {"]
    ordinal = 0
    for it in bss_items:
        emit_pad("bss", ordinal, lines)
        if it[0] == "gap":
            _, start, size = it
            u = Unit(seg, len(units), "gap", "bss@%08X" % start, bss_name, align=lowbit_align(start))
            units.append(u)
            if u.align > 16:
                lines.append("        . = ALIGN(%d);" % u.align)
            emit_keep(u.idx, lines)
            lines.append("        %s = .;" % u.label)
            lines.append("        . += 0x%X;" % size)
            lines.append("        %s = .;" % u.end_label)
        else:
            _, path, addr, size = it
            u = Unit(seg, len(units), "obj", "%s(.bss)" % path, bss_name)
            units.append(u)
            lines.append("        . = ALIGN(16);")
            emit_keep(u.idx, lines)
            lines.append("        %s = .;" % u.label)
            lines.append("        %s(.bss);" % objpath(path, build_dir))
            lines.append("        %s = .;" % u.end_label)
        ordinal += 1
    emit_pad("bss", -1, lines)
    if catch_glob:
        lines.append("        . = ALIGN(16);")
        lines.append("        __shx_%s_bss = .;" % tag)
        lines.append("        %s;" % " ".join("%s(%s)" % (catch_glob, s) for s in CATCH_BSS.split()))
        lines.append("        __shx_%s_bss_end = .;" % tag)
    lines.append("        . = ALIGN(16);")
    lines.append("    }")
    lines.append("    __sh_%s_end = ADDR(%s) + SIZEOF(%s);" % (tag, bss_name, bss_name))
    out += lines
    out += ["", "    /DISCARD/ :", "    {", "        *(*);", "    }", "}", ""]
    return "\n".join(out), units
